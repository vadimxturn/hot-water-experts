function statusFor(sub: string): PermitStatus {
  const map: Record<string, PermitStatus> = {
    Needed: "needed",
    "Docs ready": "docs_ready",
    Submitted: "submitted",
    Issued: "issued",
    "Inspection pending": "inspection_scheduled",
    "Inspection scheduled": "inspection_scheduled",
    "Inspection not booked": "issued",
    "Inspection today": "inspection_scheduled",
    Correction: "failed",
    Passed: "passed",
  };
  return map[sub] ?? "needed";
}

function currentStep(status: PermitStatus) {
  switch (status) {
    case "needed":
      return 1;
    case "docs_ready":
      return 3;
    case "submitted":
      return 4;
    case "issued":
      return 6;
    case "inspection_scheduled":
      return 8;
    case "failed":
      return 8;
    case "passed":
    case "closed":
      return 11;
    default:
      return 1;
  }
}

