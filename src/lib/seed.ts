function assertSeed(db: Database) {
  const count = (status: Lead["status"][]) => db.leads.filter((leadRow) => status.includes(leadRow.status)).length;
  const jobs = (stage: Job["stage"]) => db.jobs.filter((job) => job.stage === stage).length;
  const problems: string[] = [];
  if (count(["new", "contacted"]) !== 9) problems.push(`open leads ${count(["new", "contacted"])}`);
  if (count(["quoted"]) !== 6) problems.push(`quoted leads ${count(["quoted"])}`);
  if (jobs("scheduled") !== 9) problems.push(`scheduled ${jobs("scheduled")}`);
  if (jobs("permit") !== 7) problems.push(`permit ${jobs("permit")}`);
  if (jobs("installed") !== 5) problems.push(`installed ${jobs("installed")}`);
  if (jobs("inspected") !== 3) problems.push(`inspected ${jobs("inspected")}`);
  if (problems.length) throw new Error(`Seed counts off: ${problems.join(", ")}`);
}
