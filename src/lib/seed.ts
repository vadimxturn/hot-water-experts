function permitSteps(
  current: number,
  overrides?: { n: number; title: string; detail: string; date?: string }[],
) {
  const defaults = [
    ["Determine jurisdiction + APN", "City or county and the parcel number."],
    ["Classify scope", "Like-for-like, fuel change, tankless, or heat pump. Circuit work needs C-10."],
    ["Prepare documents", "Application data, CF1R when required, cut sheet, license, authorization."],
    ["Submit in portal", "A person reviews the pre-fill, then submits. The app does not submit alone."],
    ["Pay fee + record permit #", "Fee paid. Permit number and PDF saved on the job."],
    ["Install to code", "Straps, T&P discharge, expansion tank, venting, and the permit card on site."],
    ["Schedule inspection", "Booked in the portal. The customer is texted."],
    ["Inspection result", "Pass moves the job toward close. Fail opens correction items and a re-inspect."],
    ["Final documents", "Finaled card or screenshot, CF2R if required, install photos."],
    ["SMUD rebate (HPWH)", "Only when it applies. Needs Contractor Network membership, which is not confirmed."],
    ["Close job", "Final invoice and review request."],
  ];
  return defaults.map((row, index) => {
    const n = index + 1;
    const custom = overrides?.find((item) => item.n === n);
    const state = n < current ? "done" : n === current ? "current" : "todo";
    return {
      n,
      title: custom?.title ?? `${n}. ${row[0]}`,
      detail: custom?.detail ?? row[1],
      state: state as "done" | "current" | "todo",
      date: custom?.date,
    };
  });
}

