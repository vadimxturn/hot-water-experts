function buildPayments(jobs: Job[]): Payment[] {
  const rows: Payment[] = [];
  for (const job of jobs) {
    if (job.depositPaidAt) {
      rows.push({
        id: `pay-${job.id}-dep`,
        jobId: job.id,
        kind: "deposit",
        amount: 100,
        status: "stubbed",
        provider: "stub",
        ref: job.depositRef || "stub",
        at: job.depositPaidAt,
        note: "Demo payment. No card was charged.",
      });
    }
    if (job.payMethod === "Paid in full") {
      rows.push({
        id: `pay-${job.id}-final`,
        jobId: job.id,
        kind: "final",
        amount: Math.max(0, job.total - 100),
        status: "stubbed",
        provider: "stub",
        ref: `stub_full_${job.id.slice(-4)}`,
        at: job.depositPaidAt,
        note: "Sample paid-in-full balance.",
      });
    } else if (job.balance > 0) {
      rows.push({
        id: `pay-${job.id}-due`,
        jobId: job.id,
        kind: "final",
        amount: job.balance,
        status: "due",
        provider: "stub",
        ref: "Invoice link not sent",
        note: "Due on install day. Stripe is not connected.",
      });
    }
  }
  rows.push({
    id: "pay-refund-sample",
    jobId: "HWE-S-1019",
    kind: "refund",
    amount: 100,
    status: "refunded",
    provider: "stub",
    ref: "stub_refund_1019",
    at: "2026-10-18T15:00:00-07:00",
    note: "Sample refund record. Stripe was not called.",
  });
  return rows;
}

